//! Stable wire names and classification of findings from every rule owner.
use super::{Severity, Stage};
use serde::{Deserialize, Serialize};
use std::{fmt, ops::Deref, str::FromStr};

macro_rules! declare_findings {
    ($($variant:ident => ($name:literal, $severity:ident, $blocks:expr, $group:literal)),+ $(,)?) => {
        /// A finding emitted by a rule in this build. Serialized as its original dotted name.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
        pub enum FindingCode { $(#[serde(rename = $name)] $variant),+ }

        pub const KNOWN_CODES: &[&str] = &[$($name),+];
        impl FindingCode {
            pub const ALL: &[Self] = &[$(Self::$variant),+];
            pub const fn as_str(self) -> &'static str { match self { $(Self::$variant => $name),+ } }
            pub const fn group_title(self) -> &'static str { match self { $(Self::$variant => $group),+ } }
            pub const fn severity(self) -> Severity { match self { $(Self::$variant => Severity::$severity),+ } }
            /// The stage shared by all occurrences, if there is one. An
            /// occurrence can report its own stage (for example a required field).
            pub const fn blocks(self) -> Option<Stage> { match self { $(Self::$variant => $blocks),+ } }
        }
        impl FromStr for FindingCode {
            type Err = String;
            fn from_str(name: &str) -> Result<Self, String> {
                match name { $($name => Ok(Self::$variant)),+, _ => Err(format!("Unknown finding code {name}")) }
            }
        }
    }
}

impl Deref for FindingCode {
    type Target = str;
    fn deref(&self) -> &str {
        self.as_str()
    }
}
impl fmt::Display for FindingCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}
impl PartialEq<&str> for FindingCode {
    fn eq(&self, name: &&str) -> bool {
        self.as_str() == *name
    }
}
impl PartialEq<FindingCode> for &str {
    fn eq(&self, code: &FindingCode) -> bool {
        *self == code.as_str()
    }
}

